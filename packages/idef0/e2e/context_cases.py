"""Контекстная диаграмма с длинными подписями стрелок."""

from idef0 import Block, Context


def long_context() -> Context:
    """Создать пример с несколькими длинными подписями по всем сторонам."""
    return Context(
        block=Block("A0", "Создать\nсистему"),
        inputs=[
            "Первоначальная заявка заказчика с подробным описанием его потребностей",
            "Сведения об используемой инфраструктуре и текущих процессах организации",
        ],
        outputs=[
            "Принятая информационная система и сопроводительная документация",
            "Отчёт о выполненных работах и результатах проверки качества",
        ],
        controls=[
            "Согласованный договор и ограничения бюджета на выполнение проекта",
            "Политика информационной безопасности и требования законодательства",
        ],
        mechanisms=[
            "Команда специалистов по разработке и тестированию системы",
            "Инфраструктура разработки и средства автоматизированного тестирования",
        ],
    )
